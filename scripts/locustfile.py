"""Load profiles for the local federal-servant search API."""

from pathlib import Path
import sys

from locust import HttpUser, between, constant, task

sys.path.insert(0, str(Path(__file__).resolve().parent))
from performance_scenarios import CASES, validate_search_response


def search(client, case, *, overload=False):
    with client.get(
        "/api/servidores", params=dict(case.params),
        name=f"search/{case.label}", catch_response=True, timeout=10,
    ) as response:
        response.request_meta["name"] = f"search/{case.label} [{response.status_code}]"
        try:
            payload = response.json()
            validate_search_response(response.status_code, payload, overload=overload)
        except (ValueError, TypeError) as exc:
            # Error labels are generated by our validator, not from server responses.
            response.failure(str(exc))
        else:
            response.success()


class SmokeUser(HttpUser):
    wait_time = between(1.0, 2.0)

    @task
    def exact(self):
        search(self.client, CASES[0])

    @task
    def combined(self):
        search(self.client, CASES[5])


class SearchUser(HttpUser):
    wait_time = between(1.5, 3.0)

    @task(3)
    def exact(self):
        search(self.client, CASES[0])

    @task(2)
    def similar(self):
        search(self.client, CASES[1])

    @task(1)
    def position(self):
        search(self.client, CASES[2])

    @task(1)
    def agency(self):
        search(self.client, CASES[3])

    @task(1)
    def state(self):
        search(self.client, CASES[4])

    @task(2)
    def combined(self):
        search(self.client, CASES[5])


class OverloadUser(HttpUser):
    wait_time = constant(0.05)

    @task
    def burst(self):
        search(self.client, CASES[0], overload=True)
