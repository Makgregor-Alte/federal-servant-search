"""Measure PostgreSQL search plans without exposing query terms or rows."""
import argparse
import json
import os
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.search import build_search_queries, parse_filters


BUFFER_KEYS = (
    "Shared Hit Blocks", "Shared Read Blocks", "Shared Dirtied Blocks",
    "Shared Written Blocks", "Temp Read Blocks", "Temp Written Blocks",
)


def walk_plan(node):
    yield node
    for child in node.get("Plans", []):
        yield from walk_plan(child)


def index_names(node):
    """Collect index names from nested PostgreSQL plan nodes."""
    return sorted({item["Index Name"] for item in walk_plan(node) if item.get("Index Name")})


def plan_summary(plan):
    """Capture plan timing, row counts and buffer activity, not record data."""
    node = plan["Plan"]
    return {
        "planning_ms": round(plan["Planning Time"], 3),
        "execution_ms": round(plan["Execution Time"], 3),
        "indexes": index_names(node),
        "returned_rows": node.get("Actual Rows", 0),
        "plan_nodes": sorted({item["Node Type"] for item in walk_plan(node)
                              if item.get("Node Type")}),
        # Root PostgreSQL counters are inclusive; summing child nodes would double count.
        "buffers": {key.lower().replace(" ", "_"): node.get(key, 0)
                    for key in BUFFER_KEYS},
    }


def summarize_runs(runs):
    """Aggregate repeated plans with exact median and nearest-rank p95."""
    measurements = sorted(entry["execution_ms"] for entry in runs)
    p95_index = max(0, (95 * len(measurements) + 99) // 100 - 1)
    last = runs[-1]
    return {
        "samples": len(runs),
        "median_ms": round(statistics.median(measurements), 3),
        "min_ms": measurements[0],
        "max_ms": measurements[-1],
        "p95_ms": measurements[p95_index],
        "planning_median_ms": round(statistics.median(r["planning_ms"] for r in runs), 3),
        "indexes": sorted({idx for run in runs for idx in run["indexes"]}),
        "plan_nodes": sorted({node for run in runs for node in run["plan_nodes"]}),
        "returned_rows": last["returned_rows"],
        "buffers_last_run": last["buffers"],
    }


def search_cases(args):
    """Produce individual cases and optionally one combined case."""
    raw = {
        "nome_exato": ("nome", args.name),
        "nome_similar": ("similar", args.similar),
        "nome_padrao": ("nome", args.pattern),
        "cargo": ("cargo", args.cargo),
        "orgao": ("orgao", args.orgao),
        "uf": ("uf", args.uf),
    }
    cases = []
    for label, (key, value) in raw.items():
        if value is not None:
            case = {key: value}
            if label == "nome_padrao":
                case["name_mode"] = "pattern"
            cases.append((label, case))
    if args.combined:
        names = [name for name in ("nome_exato", "nome_similar", "nome_padrao")
                 if raw[name][1] is not None]
        if len(names) > 1:
            raise ValueError("A busca combinada aceita um unico modo de nome")
        combined = {}
        for label in names + ["cargo", "orgao", "uf"]:
            key, value = raw[label]
            if value is not None:
                combined[key] = value
                if label == "nome_padrao":
                    combined["name_mode"] = "pattern"
        if len(combined) < 2 or (len(combined) == 2 and "name_mode" in combined):
            raise ValueError("A busca combinada exige pelo menos dois filtros")
        cases.append(("combinada", combined))
    return cases


def profile_query(cursor, statement, bindings, repeats, warmups):
    """Run read-only EXPLAIN on a SQL statement generated by the search builder."""
    runs = []
    for attempt in range(repeats + warmups):
        cursor.execute("EXPLAIN (ANALYZE, BUFFERS, FORMAT JSON) " + statement, bindings)
        raw = cursor.fetchone()[0]
        if isinstance(raw, str):
            raw = json.loads(raw)
        if attempt >= warmups:
            runs.append(plan_summary(raw[0]))
    return summarize_runs(runs)


def profile_case(cursor, fields, repeats=3, warmups=1, page=1, limit=20):
    query = dict(fields, page=str(page), limit=str(limit))
    filters = parse_filters(query)
    count_sql, data_sql, count_params, data_params = build_search_queries(filters)
    return {
        "count": profile_query(cursor, count_sql, count_params, repeats, warmups),
        "results": profile_query(cursor, data_sql, data_params, repeats, warmups),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description="Mede planos SQL sem exibir dados pessoais")
    parser.add_argument("--name", help="Nome exato")
    parser.add_argument("--similar", help="Nome aproximado")
    parser.add_argument("--pattern", help="Padrao de nome com porcentagem")
    parser.add_argument("--cargo", help="Filtro de cargo")
    parser.add_argument("--orgao", help="Filtro de orgao")
    parser.add_argument("--uf", help="UF")
    parser.add_argument("--combined", action="store_true", help="Medir filtros combinados")
    parser.add_argument("--page", type=int, default=1)
    parser.add_argument("--limit", type=int, default=20)
    parser.add_argument("--repeat", type=int, default=3, help="Medicoes por consulta (1-10)")
    parser.add_argument("--warmup", type=int, default=1, help="Aquecimentos (0-3)")
    parser.add_argument("--statement-timeout-ms", type=int, default=3000)
    args = parser.parse_args(argv)
    if not 1 <= args.repeat <= 10:
        parser.error("--repeat deve estar entre 1 e 10")
    if not 0 <= args.warmup <= 3:
        parser.error("--warmup deve estar entre 0 e 3")
    if not 100 <= args.statement_timeout_ms <= 30000:
        parser.error("--statement-timeout-ms deve estar entre 100 e 30000")
    try:
        cases = search_cases(args)
        if not cases:
            parser.error("informe pelo menos um filtro")
        # All query parameters are validated before opening the database connection.
        for _, fields in cases:
            parse_filters(dict(fields, page=str(args.page), limit=str(args.limit)))
    except ValueError as exc:
        parser.error(str(exc))

    import psycopg

    results = {}
    conninfo = os.environ.get("DATABASE_URL", "")
    options = f"-c statement_timeout={args.statement_timeout_ms} -c default_transaction_read_only=on"
    with psycopg.connect(conninfo, connect_timeout=5, options=options) as conn:
        with conn.cursor() as cursor:
            cursor.execute("SET TRANSACTION READ ONLY")
            for label, fields in cases:
                results[label] = profile_case(cursor, fields, args.repeat, args.warmup,
                                              args.page, args.limit)
    print(json.dumps({"repeats": args.repeat, "warmups": args.warmup,
                      "page": args.page, "limit": args.limit, "cases": results},
                     ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
